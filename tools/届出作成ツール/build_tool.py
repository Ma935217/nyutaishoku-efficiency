def build_ledger(wb, ws, sheet, extras, db_cols, dummy):
    title(ws, f"{sheet}（{'採用者' if sheet == '入職台帳' else '退職者'}）",
          "①DB貼り付け欄に入退職管理マスタの行を【値で貼り付け】 ②黄色の追加入力を埋める ③出力する行のA列に○")
