# ================================================================ シート作成
def build():
    wb = Workbook()
    wb.remove(wb.active)
    sheets = ["使い方", "出力", "入職台帳", "退職台帳", "チェックリスト", "内容確認", "設定", "レイアウト定義",
              "コード表", "ルール", "ログ", "変更履歴"]
    S = {n: wb.create_sheet(n) for n in sheets}
    for ws in S.values():
        ws.sheet_properties.tabColor = "9DC3E6"
        ws.sheet_view.showGridLines = False if ws.title in ("使い方", "チェックリスト") else True
    for n in ("設定", "レイアウト定義", "コード表", "ルール", "ログ", "変更履歴"):
        S[n].sheet_properties.tabColor = "BFBFBF"

    build_usage(S["使い方"])
    build_settings(wb, S["設定"])
    build_layout(S["レイアウト定義"])
    build_codes(S["コード表"])
    build_ledger(wb, S["入職台帳"], "入職台帳", NYU_EXTRA, NYU_DB, NYU_DUMMY)
    build_ledger(wb, S["退職台帳"], "退職台帳", TAI_EXTRA, TAI_DB, TAI_DUMMY)
    build_output(wb, S["出力"])
    build_confirm(S["内容確認"])
    build_rules(S["ルール"])
    build_checklist(wb, S["チェックリスト"])
    build_log(S["ログ"])
    build_history(S["変更履歴"])
    wb.active = 0
    wb.save(OUT_XLSX)
    return OUT_XLSX


